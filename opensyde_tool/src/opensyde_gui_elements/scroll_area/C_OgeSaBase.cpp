//----------------------------------------------------------------------------------------------------------------------
/*! \brief   Set scroll variant and trigger QSS re-polish
   \param[in] orc_Variant Variant name for QSS targeting
*/
//----------------------------------------------------------------------------------------------------------------------
void C_OgeSaBase::SetScrollVariant(const QString & orc_Variant)
{
   this->mc_ScrollVariant = orc_Variant;
   this->style()->unpolish(this);
   this->style()->polish(this);
}

//----------------------------------------------------------------------------------------------------------------------
/*! \brief   Get current scroll variant
   \return Current variant string
*/
//----------------------------------------------------------------------------------------------------------------------
QString C_OgeSaBase::GetScrollVariant(void) const
{
   return this->mc_ScrollVariant;
}
