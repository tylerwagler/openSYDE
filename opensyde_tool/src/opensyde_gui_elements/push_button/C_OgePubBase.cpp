//----------------------------------------------------------------------------------------------------------------------
/*! \brief   Set button variant and trigger QSS re-polish
   \param[in] orc_Variant Variant name for QSS targeting
*/
//----------------------------------------------------------------------------------------------------------------------
void C_OgePubBase::SetButtonVariant(const QString & orc_Variant)
{
   this->mc_ButtonVariant = orc_Variant;
   this->style()->unpolish(this);
   this->style()->polish(this);
}

//----------------------------------------------------------------------------------------------------------------------
/*! \brief   Get current button variant
   \return Current variant string
*/
//----------------------------------------------------------------------------------------------------------------------
QString C_OgePubBase::GetButtonVariant(void) const
{
   return this->mc_ButtonVariant;
}
